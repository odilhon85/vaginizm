/* Language management */
let currentLang = (localStorage.getItem('gino_lang') || 'lat');

function createLangButton(code) {
  const active = code === currentLang;
  const btn = document.createElement('button');
  btn.textContent = DICT[code].langLabel;
  btn.style.cssText = `border:1px solid #6B2737;border-radius:999px;padding:7px 15px;font-size:13px;font-weight:500;transition:all .25s ease;background:${active?'#6B2737':'transparent'};color:${active?'#FBF7F2':'#6B2737'}`;
  btn.onclick = () => { currentLang = code; localStorage.setItem('gino_lang', code); render(); };
  return btn;
}

function renderLangSwitcher() {
  /* Desktop header */
  const el = document.getElementById('lang-switcher');
  if (el) {
    el.innerHTML = '';
    ['cyr','lat','lat26'].forEach(code => { el.appendChild(createLangButton(code)); });

    const phone = document.createElement('a');
    phone.href = 'tel:+998997663433';
    phone.textContent = DICT[currentLang].navPhone;
    phone.style.cssText = 'margin-left:6px;border:1px solid #6B2737;border-radius:999px;padding:9px 16px;font-size:14px;font-weight:700;color:#6B2737';
    el.appendChild(phone);
  }

  /* Mobile menu */
  const mobileEl = document.getElementById('mobile-lang-switcher');
  if (mobileEl) {
    mobileEl.innerHTML = '';
    ['cyr','lat','lat26'].forEach(code => { mobileEl.appendChild(createLangButton(code)); });
  }
}

/* Mobile header expand/collapse with icon change */
document.addEventListener('DOMContentLoaded', () => {
  const btn = document.getElementById('mobile-menu-btn');
  const header = document.getElementById('site-header');
  if (!btn || !header) return;

  /* Toggle menu on button click and change icon between ≡ and ✕ */
  btn.addEventListener('click', (e) => {
    e.stopPropagation();
    const isOpen = header.classList.toggle('open');
    updateMenuIcon(isOpen);
  });

  function updateMenuIcon(open) {
    if (open) {
      /* Show close icon */
      btn.textContent = '✕';
      btn.style.fontSize = '20px';
      btn.style.color = '#6B2737';
      btn.style.display = 'flex';
      btn.style.alignItems = 'center';
      btn.style.justifyContent = 'center';
      btn.style.transform = 'none';
    } else {
      /* Back to three horizontal lines */
      btn.textContent = '';
      delete btn.style.fontSize;
      delete btn.style.color;
      btn.style.transform = 'none';
      btn.innerHTML = '<span></span><span></span><span></span>';
    }
  }

  /* Close when tapping outside the header */
  document.addEventListener('click', (e) => {
    if (!header.contains(e.target)) {
      if (header.classList.contains('open')) {
        header.classList.remove('open');
        updateMenuIcon(false);
      }
    }
  });
});

/* Render all content */
function render() {
  const cur = DICT[currentLang];
  if (!cur) return;

  document.documentElement.lang = currentLang === 'cyr' ? 'uz-Cyrl' : 'uz';

  /* i18n attributes */
  document.querySelectorAll('[data-i18n]').forEach(elm => {
    const key = elm.getAttribute('data-i18n');
    if (cur[key] !== undefined) elm.textContent = cur[key];
  });

  /* Telegram CTA (always update with current language) */
  const tgBtn = document.getElementById('telegram-cta');
  if (tgBtn) {
    tgBtn.textContent = cur.ctaTelegram || cur.telegramText;
  }

  /* Final CTA */
  const finalBtn = document.getElementById('final-cta-btn');
  if (finalBtn) {
    finalBtn.textContent = cur.ctaButton + ': ' + cur.navPhone;
  }

  /* Why list */
  const whyEl = document.getElementById('why-list');
  if (whyEl) {
    whyEl.innerHTML = '';
    cur.why.forEach(t => {
      const row = document.createElement('div');
      row.className = 'why-row';
      row.innerHTML = `<div class="why-icon">✓</div><div class="why-text">${t}</div>`;
      whyEl.appendChild(row);
    });
  }

  /* FAQ */
  const faqEl = document.getElementById('faq-list');
  if (faqEl) {
    faqEl.innerHTML = '';
    cur.faq.forEach(([q,a]) => {
      const item = document.createElement('div');
      item.className = 'faq-item glass-chip';
      item.innerHTML = `<div class="faq-q"><span>${q}</span><span>+</span></div><div class="faq-a">${a}</div>`;
      item.onclick = () => {
        item.classList.toggle('open');
        const icon = item.querySelector('.faq-q span:last-child');
        if (icon) icon.textContent = item.classList.contains('open') ? '−' : '+';
      };
      faqEl.appendChild(item);
    });
  }

  /* Map links */
  const gLink = document.getElementById('google-link');
  const yLink = document.getElementById('yandex-link');
  if (gLink) gLink.textContent = cur.googleLabel;
  if (yLink) yLink.textContent = cur.yandexLabel;

  /* Footer */
  const footerLine = document.getElementById('footer-line');
  if (footerLine) footerLine.textContent = cur.footer;

  renderLangSwitcher();
}

/* Blur-up effect for smooth image loading */
function initBlurUp() {
  document.querySelectorAll('.blur-up').forEach(img => {
    if (img.complete) {
      img.classList.add('loaded');
    } else {
      img.addEventListener('load', () => img.classList.add('loaded'), { once: true });
      img.addEventListener('error', () => img.classList.add('loaded'), { once: true });
    }
  });
}

/* Init */
document.addEventListener('DOMContentLoaded', () => {
  render();
  initBlurUp();
});
